"""### 2.4.1 Quantifying Outliers (IQR Method)

Figure 7 shows outliers visually, but for the report we also quantify them numerically using the standard IQR rule: a value is flagged as an outlier if it falls below `Q1 - 1.5*IQR` or above `Q3 + 1.5*IQR`. These are **not treated as data errors** — in this dataset, high `avg_glucose_level` and `bmi` values correspond to genuinely diabetic/obese patients, who are clinically relevant to stroke risk rather than noise to be removed. They are therefore kept in the dataset; the decision on how to *handle* them (without deleting them) is addressed in Section 3.3.
"""

outlier_summary = []
for col in numeric_cols_eda:
    q1, q3 = df[col].quantile([0.25, 0.75])
    iqr = q3 - q1
    lower, upper = q1 - 1.5 * iqr, q3 + 1.5 * iqr
    n_outliers = ((df[col] < lower) | (df[col] > upper)).sum()
    outlier_summary.append({
        "feature": col, "Q1": round(q1, 2), "Q3": round(q3, 2),
        "lower_bound": round(lower, 2), "upper_bound": round(upper, 2),
        "n_outliers": n_outliers, "pct_outliers": round(n_outliers / len(df) * 100, 2)
    })

outlier_df = pd.DataFrame(outlier_summary)
