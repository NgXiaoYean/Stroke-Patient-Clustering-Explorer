"""## 4. Dimensionality Reduction (PCA)

One-hot encoding expands the categorical columns into many sparse binary features, which can dilute distance calculations and slow DBSCAN down. Principal Component Analysis (PCA) is applied to compress the processed feature matrix down to the components that jointly explain at least 90% of the total variance, while a separate 2-component projection is kept purely for visualization in Section 6.
"""

pca_full = PCA(random_state=RANDOM_STATE).fit(X_processed)
cum_var = np.cumsum(pca_full.explained_variance_ratio_)
n_components = int(np.argmax(cum_var >= 0.90) + 1)
print(f"Components needed for 90% variance: {n_components}")

pca = PCA(n_components=n_components, random_state=RANDOM_STATE)
X_pca = pca.fit_transform(X_processed)

# Separate 2D projection kept only for the scatter plot in Section 6
pca_2d = PCA(n_components=2, random_state=RANDOM_STATE)
X_2d = pca_2d.fit_transform(X_processed)

