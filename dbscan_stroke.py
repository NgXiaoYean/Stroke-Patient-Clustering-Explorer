"""## 3. Data Preprocessing

Guided by the EDA above, the following preprocessing steps are applied:

- **Numeric features with outliers** (`age`, `avg_glucose_level`, `bmi`) -> `RobustScaler`, which scales using the median and interquartile range (IQR) instead of the mean and standard deviation. This was chosen specifically because Section 2.4.1 identified outliers in `avg_glucose_level` and `bmi`; `RobustScaler` reduces their influence on distance calculations without deleting any patient records, preserving the high-glucose/high-BMI patients who are most relevant to stroke risk.
- **Binary clinical features** (`hypertension`, `heart_disease`) -> `StandardScaler`, since these are already 0/1 flags with no outlier concern.
- **Categorical features** -> `OneHotEncoder`, since DBSCAN operates on numeric distances and cannot use raw category labels directly.
- `stroke` is held out entirely and only reintroduced later (Section 8) to *interpret* the clusters — it is never used to form them.
"""

stroke_label = df["stroke"].copy()
X_raw = df.drop(columns=["stroke"])

numeric_cols = ["age", "avg_glucose_level", "bmi"]   # outlier-prone -> RobustScaler
binary_cols = ["hypertension", "heart_disease"]       # already 0/1 -> StandardScaler
categorical_cols = ["gender", "ever_married", "work_type", "Residence_type", "smoking_status"]

preprocessor = ColumnTransformer(
    transformers=[
        ("num", RobustScaler(), numeric_cols),
        ("bin", StandardScaler(), binary_cols),
        ("cat", OneHotEncoder(drop=None, handle_unknown="ignore"), categorical_cols),
    ]
)
X_processed = preprocessor.fit_transform(X_raw)
# OneHotEncoder can return a sparse matrix; densify for downstream PCA/DBSCAN use
if hasattr(X_processed, "toarray"):
    X_processed = X_processed.toarray()

# Reduce to 2 dimensions for stable DBSCAN and plotting
pca = PCA(n_components=2, random_state=42)
X_pca = pca.fit_transform(X_processed)

print("Data successfully preprocessed and reduced to 2 dimensions!")

print("Processed feature matrix shape:", X_processed.shape)

def show_transformation(column_name):
    feature_names = preprocessor.get_feature_names_out()

    print("=" * 60)
    print(f"Original Column: {column_name}")

    if column_name in numeric_cols:
        print("Transformation Method: RobustScaler (median/IQR-based, robust to outliers)")
    elif column_name in binary_cols:
        print("Transformation Method: StandardScaler")
    elif column_name in categorical_cols:
        print("Transformation Method: One-Hot Encoding")

    print("-" * 60)
    print("New Feature(s) After Transformation:")

    matching_features = [
        feature.replace("num__", "").replace("bin__", "").replace("cat__", "")
        for feature in feature_names
        if column_name.lower() in feature.lower()
    ]

    for i, feature in enumerate(matching_features, 1):
        print(f"{i}. {feature}")

    print("=" * 60)


# Test
