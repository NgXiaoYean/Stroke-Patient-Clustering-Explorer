"""## 9b. Identifying High-Risk Patient Groups

This step directly addresses the project goal: having discovered patient groups based purely on lifestyle and clinical characteristics (Sections 5-6), we now check whether any group shows a stroke rate meaningfully above the dataset's overall rate. A cluster is flagged as **elevated-risk** if its stroke rate exceeds the overall rate by a chosen margin (default: 1.5x).
"""

RISK_MULTIPLIER = 1.5  # a cluster is "elevated-risk" if its stroke rate > 1.5x the overall rate

overall_rate = df["stroke"].mean() * 100
